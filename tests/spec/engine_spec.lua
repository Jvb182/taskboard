local T, Mock = ...

local function col(ns, card)
    local board = ns.DB:GetActiveBoard()
    return ns.DB:CardRole(board, card)
end

describe("Live tracking: Get 20 Peacebloom", function()
    it("keeps separate targets for two cards tracking the same item", function()
        local m, ns = T.client()
        local three = ns.Commands:Add("Get 3 Peacebloom")
        local five = ns.Commands:Add("Get 5 Peacebloom")
        m.Loot(2447, 3); m.Advance(1)
        T.eq(three.progress.cur, 3); T.eq(three.progress.target, 3)
        T.eq(five.progress.cur, 3); T.eq(five.progress.target, 5)
        T.eq(col(ns, three), "done"); T.eq(col(ns, five), "doing")
        m.Loot(2447, 2); m.Advance(1)
        T.eq(col(ns, five), "done"); T.eq(five.progress.target, 5)
        T.noErrors(ns)
    end)

    it("counts 0 -> 5 -> 20 as you loot, moves the card and celebrates", function()
        local m, ns = T.client()
        local card = ns.Commands:Add("Get 20 Peacebloom #herbs")
        m.Advance(0.5)
        T.eq(card.progress.text, "Peacebloom 0/20")
        T.eq(col(ns, card), "todo")

        m.Loot(2447, 5)
        m.Advance(0.5)
        T.eq(card.progress.cur, 5)
        T.eq(card.progress.text, "Peacebloom 5/20")
        T.near(card.progress.frac, 0.25)
        T.eq(col(ns, card), "doing", "auto-started when progress began")
        T.eq(m.errorsFrame[#m.errorsFrame], "Peacebloom 5/20", "quest-style progress message")

        m.Loot(2447, 14)
        m.Advance(0.5)
        T.eq(card.progress.text, "Peacebloom 19/20")
        T.eq(col(ns, card), "doing")

        m.Loot(2447, 1)
        m.Advance(1)
        T.eq(card.progress.done, true)
        T.eq(col(ns, card), "done", "auto-completed")
        T.eq(m.errorsFrame[#m.errorsFrame], "Peacebloom 20/20 (Complete)")
        T.eq(ns.DB:GetActiveBoard().order.done[1], card.id, "lands on top of Done")
        T.ok(#ns.Toast:Active() >= 1, "completion toast shown")
        T.ok(m.ChatContains("Complete:"), "completion printed to chat")
        T.ok(#m.sounds >= 1, "sound played")
        T.eq(ns.db.stats.total, 1, "recorded in stats")
        T.eq(ns.Stats:Summary().streak, 1)
        T.noErrors(ns)
    end)

    it("throttles many bag events into one evaluation pass", function()
        local m, ns = T.client()
        ns.Commands:Add("Get 50 Peacebloom")
        m.Advance(1)
        local before = ns.Engine.stats.passes
        for _ = 1, 25 do m.Loot(2447, 1) end
        m.Advance(1)
        T.eq(ns.Engine.stats.passes - before, 1)
    end)

    it("counts the bank when enabled", function()
        local m, ns = T.client()
        m.state.bank[2447] = 15
        local card = ns.Commands:Add("Get 20 Peacebloom")
        m.Advance(0.5)
        T.eq(card.progress.cur, 15)
        ns.db.settings.includeBank = false
        ns.Engine:MarkAll()
        m.Advance(0.5)
        T.eq(card.progress.cur, 0)
    end)

    it("binds an unknown item name the first time it is looted", function()
        local m, ns = T.client()
        local card = ns.Commands:Add("Get 3 Mystery Widget")
        T.eq(card.goal.itemID, nil)
        m.Advance(0.5)
        T.contains(card.progress.text, "not looted yet")
        m.Loot(9999, 2)
        m.Advance(0.5)
        T.eq(card.goal.itemID, 9999)
        T.eq(card.progress.text, "Mystery Widget 2/3")
        T.noErrors(ns)
    end)

    it("does not move back out of Done when the count drops, but flags it", function()
        local m, ns = T.client()
        local card = ns.Commands:Add("Get 5 Peacebloom")
        m.Loot(2447, 5)
        m.Advance(1)
        T.eq(col(ns, card), "done")
        m.RemoveItem(2447, 3)
        m.Advance(1)
        T.eq(col(ns, card), "done")
        T.eq(card._regressed, true)
    end)

    it("respects a manual move out of Done", function()
        local m, ns = T.client()
        local board = ns.DB:GetActiveBoard()
        local card = ns.Commands:Add("Get 5 Peacebloom")
        m.Loot(2447, 5)
        m.Advance(1)
        ns.DB:MoveCard(board, card.id, "todo")
        m.Loot(2447, 1)
        m.Advance(1)
        T.eq(col(ns, card), "todo", "not re-completed while still complete")
        m.RemoveItem(2447, 6)
        m.Advance(1)
        m.Loot(2447, 5)
        m.Advance(1)
        T.eq(col(ns, card), "done", "completes again after dropping below and refilling")
    end)

    it("honors the autoStart and autoComplete settings", function()
        local m, ns = T.client()
        ns.db.settings.autoStart, ns.db.settings.autoComplete = false, false
        local card = ns.Commands:Add("Get 5 Peacebloom")
        m.Loot(2447, 5)
        m.Advance(1)
        T.eq(col(ns, card), "todo")
        T.eq(card.progress.done, true)
    end)

    it("tracks subtask goals and completes the card when all are done", function()
        local m, ns = T.client()
        local card = ns.Commands:Add("Alchemy prep; 4 Peacebloom; 2 Silverleaf; buy vials")
        m.Advance(0.5)
        m.Loot(2447, 4)
        m.Advance(0.5)
        T.eq(card.subtasks[1].done, true, "subtask checks itself")
        T.eq(col(ns, card), "doing")
        m.Loot(765, 2)
        m.Advance(0.5)
        T.eq(card.subtasks[2].done, true)
        T.eq(col(ns, card), "doing", "manual subtask still open")
        local board = ns.DB:GetActiveBoard()
        local subs = ns.Util.DeepCopy(card.subtasks)
        subs[3].done = true
        ns.DB:UpdateCard(board, card, { subtasks = subs })
        m.Advance(0.5)
        T.eq(col(ns, card), "done")
        T.noErrors(ns)
    end)

    it("does not evaluate cards that belong to another character", function()
        local m, ns = T.client()
        local board = ns.DB:GetActiveBoard()
        local card = ns.DB:AddCard(board, { title = "Alt herbs", char = "Altchar-Forever",
            goal = { type = "item", itemID = 2447, name = "Peacebloom", target = 5 },
            progress = { cur = 3, target = 5, frac = 0.6, text = "Peacebloom 3/5", t = 1 } })
        m.Loot(2447, 10)
        m.Advance(1)
        T.eq(card.progress.cur, 3, "alt's last-known progress kept")
        T.eq(col(ns, card), "todo")
    end)

    it("survives a goal whose evaluation throws", function()
        local m, ns = T.client()
        local good = ns.Commands:Add("Get 2 Peacebloom")
        local board = ns.DB:GetActiveBoard()
        local bad = ns.DB:AddCard(board, { title = "boom", goal = { type = "item", itemID = 765, name = "Silverleaf", target = 1 } })
        local real = m.env.C_Item.GetItemCount
        m.env.C_Item.GetItemCount = function(id, ...)
            if id == 765 then error("simulated client error") end
            return real(id, ...)
        end
        m.Loot(2447, 2)
        m.Advance(1)
        T.eq(good.progress.done, true, "other cards still update")
        m.env.C_Item.GetItemCount = real
    end)
end)


