local T, Mock = ...

local function cardFrame(ns, card)
    for _, f in ipairs(ns.Board:Internals().cards) do
        if f.card == card then return f end
    end
end

local function enter(box, text)
    box:SetText(text)
    box:GetScript("OnEnterPressed")(box)
end

local function menuRow(m, text)
    local menu = m.env.TaskboardMenu
    T.ok(menu and menu:IsShown(), "menu is open")
    for _, row in ipairs(menu.rows) do
        if row:IsShown() and row.text:GetText():find(text, 1, true) then return row end
    end
    error("no menu row '" .. text .. "'")
end

