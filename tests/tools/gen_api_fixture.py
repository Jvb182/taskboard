"""Builds tests/fixtures/forever_api.lua from Blizzard's generated API docs.

The fixture lets the offline tests check that every C_ API, global API, event,
widget method, XML template and SOUNDKIT constant Taskboard uses really exists
in the WoW: Forever client, without launching the game.

Usage:
    git clone --depth 1 --branch forever --filter=blob:none --sparse \
        https://github.com/Gethe/wow-ui-source ui-src
    (cd ui-src && git sparse-checkout set Interface/AddOns/Blizzard_APIDocumentationGenerated \
        Interface/AddOns/Blizzard_SharedXML Interface/AddOns/Blizzard_ObjectAPI \
        Interface/AddOns/Blizzard_ChatFrameBase Interface/AddOns/Blizzard_SharedXMLBase \
        Interface/AddOns/Blizzard_FrameXML Interface/AddOns/Blizzard_FrameXMLBase \
        Interface/AddOns/Blizzard_UIParent)
    python tests/tools/gen_api_fixture.py ui-src
The docs are parsed as text and never executed.
"""
import glob
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "fixtures", "forever_api.lua")

HEADER_NAME = re.compile(r'^\tName = "(\w+)",', re.M)
HEADER_TYPE = re.compile(r'^\tType = "(\w+)",', re.M)
HEADER_NS = re.compile(r'^\tNamespace = "(\w+)",', re.M)
# A function may override its file's namespace (Namespace = "" means a global).
FUNCTION = re.compile(r'^\t\t\tName = "(\w+)",\s*\n\t\t\tType = "Function",[ \t\r]*\n(?:\t\t\tNamespace = "(\w*)",)?', re.M)
EVENT = re.compile(r'LiteralName = "(\w+)"')


def main(src):
    addons = os.path.join(src, "Interface", "AddOns")
    docs = os.path.join(addons, "Blizzard_APIDocumentationGenerated")
    namespaces, globals_, events, widgets = {}, set(), set(), {}
    for path in sorted(glob.glob(os.path.join(docs, "*.lua"))):
        with open(path, encoding="utf-8") as f:
            text = f.read()
        name, kind, ns = HEADER_NAME.search(text), HEADER_TYPE.search(text), HEADER_NS.search(text)
        if not name:
            continue
        for m in FUNCTION.finditer(text):
            fn, override = m.group(1), m.group(2)
            space = override if override is not None else (ns.group(1) if ns else "")
            if kind and kind.group(1) == "ScriptObject":
                widgets.setdefault(name.group(1), set()).add(fn)
            elif space:
                namespaces.setdefault(space, set()).add(fn)
            else:
                globals_.add(fn)
        events.update(EVENT.findall(text))

    templates = set()
    for path in glob.glob(os.path.join(addons, "**", "*.xml"), recursive=True):
        with open(path, encoding="utf-8", errors="ignore") as f:
            for m in re.finditer(r'<(\w+)\s+[^>]*name="([A-Za-z0-9_]+)"[^>]*virtual="true"', f.read()):
                templates.add((m.group(2), m.group(1)))

    sounds = set()
    for path in glob.glob(os.path.join(addons, "Blizzard_SharedXML", "**", "SoundKitConstants.lua"), recursive=True):
        with open(path, encoding="utf-8") as f:
            sounds.update(re.findall(r"^\s*([A-Z0-9_]+)\s*=\s*\d+", f.read(), re.M))

    # Lua-defined global helpers Taskboard may call (defined in FrameXML, not C).
    lua_globals = set()
    for path in glob.glob(os.path.join(addons, "**", "*.lua"), recursive=True):
        with open(path, encoding="utf-8", errors="ignore") as f:
            text = f.read()
            for m in re.finditer(r"^function\s+([A-Za-z_][A-Za-z0-9_.]*)\s*\(", text, re.M):
                lua_globals.add(m.group(1))
            # Top-level assignments such as "PlaySound = C_Sound.PlaySound;"
            for m in re.finditer(r"^([A-Za-z_][A-Za-z0-9_]*)\s*=[^=]", text, re.M):
                lua_globals.add(m.group(1))

    try:
        rev = subprocess.check_output(["git", "-C", src, "log", "-1", "--format=%s"], text=True).strip()
    except Exception:
        rev = "unknown"

    def lset(items):
        return "{" + ",".join('["%s"]=true' % i for i in sorted(items)) + "}"

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Generated by tests/tools/gen_api_fixture.py from Gethe/wow-ui-source (forever).\n")
        f.write("-- Source build: %s\n" % rev)
        f.write("return {\n  build = %r,\n" % rev)
        f.write("  namespaces = {\n")
        for ns in sorted(namespaces):
            f.write("    %s = %s,\n" % (ns, lset(namespaces[ns])))
        f.write("  },\n  globals = %s,\n" % lset(globals_))
        f.write("  events = %s,\n" % lset(events))
        f.write("  widgets = {\n")
        for w in sorted(widgets):
            f.write("    %s = %s,\n" % (w, lset(widgets[w])))
        f.write("  },\n  templates = {" + ",".join('["%s"]="%s"' % t for t in sorted(templates)) + "},\n")
        f.write("  soundkit = %s,\n" % lset(sounds))
        f.write("  luaGlobals = %s,\n}\n" % lset(lua_globals))
    print("wrote", OUT, "namespaces", len(namespaces), "globals", len(globals_), "events", len(events),
          "widgets", len(widgets), "templates", len(templates), "sounds", len(sounds), "luaGlobals", len(lua_globals))


if __name__ == "__main__":
    main(sys.argv[1])

